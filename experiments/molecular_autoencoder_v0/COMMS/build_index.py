#!/usr/bin/env python3
"""Regenerate COMMS/INDEX.md from INBOX.md and ACK.md.

WHY THIS IS GENERATED AND NOT WRITTEN BY HAND. INBOX.md is 7,600+ lines and
append-only, and it is the project's actual reasoning record -- but with 96 items and
no index, finding "where was the rate result retracted" means grepping. A hand-kept
index solves that once and then goes stale silently, which is the same defect class as
every other one on this record: a thing that was true when it was written and stopped
being true without saying so.

WHY IT IS A SEPARATE FILE. Putting the index at the top of INBOX.md would put a
rewritten block in a file that two agents append to, so every regeneration would
conflict with an append. INDEX.md is derived, INBOX.md stays append-only, and neither
touches the other.

    python COMMS/build_index.py          # rewrites COMMS/INDEX.md
    python COMMS/build_index.py --check  # exit 1 if stale, for a hook or CI
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
INBOX, ACK, INDEX = HERE / "INBOX.md", HERE / "ACK.md", HERE / "INDEX.md"

ITEM = re.compile(r"^## (\d+)\s*[—-]\s*(.+?)\s*$")
# Items whose own title says they overturn something. Kept deliberately loose: the
# point is to make retractions VISIBLE in the index, not to classify them precisely.
OVERTURNS = re.compile(r"retract|withdraw|correct|wrong|refut|supersed", re.I)


def parse_items(text):
    out = []
    for n, line in enumerate(text.splitlines(), 1):
        m = ITEM.match(line)
        if m:
            out.append({"num": int(m.group(1)), "line": n, "title": m.group(2)})
    return out


def last_acted(text):
    m = re.search(r"^last_acted:\s*(\d+)", text, re.M)
    return int(m.group(1)) if m else None


def build():
    items = parse_items(INBOX.read_text())
    acted = last_acted(ACK.read_text()) if ACK.exists() else None
    if not items:
        raise SystemExit("build_index: no '## NNN — title' headers found in INBOX.md")

    open_items = [i for i in items if acted is not None and i["num"] > acted]
    rows = [
        "# INBOX index",
        "",
        "Generated by `COMMS/build_index.py` -- do not edit by hand; re-run it instead.",
        "",
        f"{len(items)} items. Highest is **{items[-1]['num']:03d}**; "
        f"`ACK.md` records `last_acted: {acted:03d}`."
        if acted is not None else f"{len(items)} items.",
        "",
    ]

    if open_items:
        rows += [
            f"**Open ({len(open_items)}):** "
            + ", ".join(f"[{i['num']:03d}](#{i['num']:03d})" for i in open_items),
            "",
            "An item above `last_acted` has not been read by the cluster agent. That is not",
            "the same as an item it disagreed with, and the distinction is the point of the",
            "ledger -- silence is indistinguishable from refusal unless one of them is recorded.",
            "",
        ]

    rows += [
        "`*` marks an item whose own title says it overturns something. This record",
        "contains several reversals and at least one reversal of a reversal, so a reader",
        "arriving at any single item needs to know it may not be the last word.",
        "",
        "| # | | item | line |",
        "|---|---|---|---|",
    ]
    for i in items:
        flag = "*" if OVERTURNS.search(i["title"]) else ""
        status = "" if acted is None or i["num"] <= acted else " **[open]**"
        title = i["title"].replace("|", "\\|")
        rows.append(f'| <a id="{i["num"]:03d}"></a>{i["num"]:03d} | {flag} | {title}{status} '
                    f'| [L{i["line"]}](INBOX.md#L{i["line"]}) |')
    return "\n".join(rows) + "\n"


if __name__ == "__main__":
    new = build()
    if "--check" in sys.argv:
        cur = INDEX.read_text() if INDEX.exists() else ""
        if cur != new:
            print("build_index: INDEX.md is stale -- run COMMS/build_index.py", file=sys.stderr)
            raise SystemExit(1)
        print("build_index: INDEX.md is current")
    else:
        INDEX.write_text(new)
        n = new.count("\n| <a id=")
        print(f"build_index: wrote {INDEX.relative_to(HERE.parent)} with {n} items")
